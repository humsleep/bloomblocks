export const STRINGS: Readonly<Record<Lang, Dict>> = BASE;

/**
 * The language for ONE BCP-47 tag (as iOS / navigator give them: "zh-Hant-TW", "zh_TW", "it-CH",
 * "es-419", "yue-Hant-HK"), or null when we do not ship it.
 * Chinese: the script subtag wins (zh-Hant-* → zh-Hant, zh-Hans-* → zh-Hans, whatever the region);
 * without one, the region decides — TW / HK / MO → zh-Hant, everything else (CN, SG, MY, plain "zh")
 * → zh-Hans. Cantonese (yue) is written in Traditional characters unless it says Hans.
 * Spanish: one neutral "es" for every region. Portuguese: pt-BR for every region.
 */
export function langOf(raw: string | null | undefined): Lang | null {
  if (!raw) return null;
  const parts = raw.trim().replace(/_/g, "-").toLowerCase().split("-").filter(Boolean);
  const base = parts[0];
  if (!base) return null;
  if (base === "zh" || base === "cmn" || base === "yue") {
    const rest = parts.slice(1);
    if (rest.includes("hant")) return "zh-Hant";
    if (rest.includes("hans")) return "zh-Hans";
    if (rest.some((p) => p === "tw" || p === "hk" || p === "mo")) return "zh-Hant";
    return base === "yue" ? "zh-Hant" : "zh-Hans";
  }
  if (base === "pt") return "pt-BR"; // the only Portuguese we ship
  return LANGS.find((l) => l === base) ?? null;
}

/** Best supported language for a list of BCP-47 tags (first match wins), English fallback. */
export function pickLang(tags: readonly (string | null | undefined)[]): Lang {
  for (const raw of tags) {
    const hit = langOf(raw);
    if (hit) return hit;
  }
  return "en";
}

/** Chinese / Japanese: no spaces between words, full-width list punctuation. */
export function isCJK(lang: Lang): boolean {
  return lang === "ja" || lang === "zh-Hans" || lang === "zh-Hant";
}

/** Separator between the parts of one spoken label ("Row 1, column 2, lit"). */
export function listSep(lang: Lang): string {
  return lang === "ja" ? "、" : lang === "zh-Hans" || lang === "zh-Hant" ? "，" : ", ";
}

/** Separator between queued announcements. */
export function sentenceSep(lang: Lang): string {
  return isCJK(lang) ? "。" : ". ";
}

export function format(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const s = STRINGS[lang][key] ?? en[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}
