// Writes ios/identity.xcconfig from app.identity.json (the single source of
// bundle id / display name / team id). Run by `npm run ios:sync`.
// Build/marketing numbers live in ios/version.xcconfig (scripts/bump-build.mjs).
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const id = JSON.parse(readFileSync(new URL("app.identity.json", root), "utf8"));
const out = `// GENERATED by scripts/apply-identity.mjs from app.identity.json. Do not edit.
#include "version.xcconfig"
APP_BUNDLE_ID = ${id.bundleId}
APP_DISPLAY_NAME = ${id.appName}
APP_TEAM_ID = ${id.teamId}
`;
writeFileSync(new URL("ios/identity.xcconfig", root), out);
const ver = new URL("ios/version.xcconfig", root);
if (!existsSync(ver)) {
  writeFileSync(ver, "// Written by scripts/bump-build.mjs. APP_BUILD_NUMBER = CFBundleVersion, APP_MARKETING_VERSION = CFBundleShortVersionString.\nAPP_MARKETING_VERSION = 1.0\nAPP_BUILD_NUMBER = 1\n");
}
console.log(`identity: ${id.appName} ${id.bundleId} (team ${id.teamId})`);
