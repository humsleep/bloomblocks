// One command for the app's static native art (re-run after a designer edits the SVG):
//   npm run art            (= node scripts/make-art.mjs [path/to/icon.svg])
//
// 1. App icon from the chosen designer SVGs in docs/icon/ (or another dir given as argv[2]):
//      duskwick-icon.svg        → resources/icon/AppIcon-1024.png         Any: OPAQUE, alpha channel stripped
//      duskwick-icon-dark.svg   → resources/icon/AppIcon-Dark-1024.png    Dark: transparent background (iOS draws the dark backdrop)
//      duskwick-icon-tinted.svg → resources/icon/AppIcon-Tinted-1024.png  Tinted: grayscale on transparent (iOS applies the tint)
//    and copies them into ios/App/App/Assets.xcassets/AppIcon.appiconset (single-size 1024 entries).
// 2. Launch image (UX P2-16): resources/launch/launch-dusk.svg → .png, the dusk sky + hill
//    silhouettes of the first game frame (same palette and hill curves as src/render/backdrop.ts,
//    laid out for the usual portrait phone proportions), copied to Assets.xcassets/LaunchDusk.imageset.
//
// Rasteriser: Playwright's bundled Chromium (already a devDependency; free, local, exact SVG
// gradients/masks). Alpha is stripped with macOS `sips` (PNG → JPEG q100 → PNG would lose
// quality, so instead we render the opaque variant on an opaque page and drop alpha by a
// BMP round-trip, which is lossless).
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const here = dirname(fileURLToPath(import.meta.url));
const client = resolve(here, "..");
const repo = resolve(client, "../..");
const iconDir = resolve(process.argv[2] ?? resolve(repo, "docs/icon"));
const svgPath = resolve(iconDir, "duskwick-icon.svg");
const iconOut = resolve(client, "resources/icon");
const launchOut = resolve(client, "resources/launch");
const xcassets = resolve(client, "ios/App/App/Assets.xcassets");

// palette (mirror of src/render/palette.ts — read it so a palette change flows through)
const palSrc = readFileSync(resolve(client, "src/render/palette.ts"), "utf8");
const PAL = Object.fromEntries([...palSrc.matchAll(/^\s+(\w+): "(#[0-9A-Fa-f]{6})"/gm)].map((m) => [m[1], m[2]]));
const mix = (a, b, t) => {
  const p = (c) => [1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16));
  const [x, y] = [p(a), p(b)];
  return "#" + x.map((v, i) => Math.round(v + (y[i] - v) * t).toString(16).padStart(2, "0")).join("");
};

// ---------- launch image (points: 390 x 844, rendered @2x+) ----------
function launchSvg() {
  const W = 390, H = 844, u = 1;
  // proportions of the first frame on a 19.5:9 phone (playtest/shots): house base ≈ 45 % of H
  const houseBaseY = Math.round(H * 0.45);
  const horizon = houseBaseY - 40 * u;
  const crestY = houseBaseY + 12 * u;
  const hillPts = (baseY, amp, phase, freq) => {
    const pts = [];
    for (let i = 0; i <= 48; i++) {
      const x = (W * i) / 48, t = x / W;
      const y = baseY - amp * (0.6 * Math.sin(t * Math.PI * freq + phase) + 0.4 * Math.sin(t * Math.PI * freq * 2.3 + phase * 1.7));
      pts.push(`${x.toFixed(1)},${y.toFixed(1)}`);
    }
    return `M0,${H} L${pts.join(" L")} L${W},${H} Z`;
  };
  const skyEnd = horizon + 30 * u;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <!-- GENERATED by scripts/make-art.mjs from src/render/palette.ts + backdrop.ts curves. -->
  <defs>
    <linearGradient id="sky" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="0" y2="${skyEnd}">
      <stop offset="0" stop-color="${PAL.skyNight}"/><stop offset="0.42" stop-color="${PAL.skyDusk}"/>
      <stop offset="0.78" stop-color="${mix(PAL.skyDusk, PAL.skyHorizon, 0.55)}"/><stop offset="1" stop-color="${PAL.skyHorizon}"/>
    </linearGradient>
    <radialGradient id="haze" gradientUnits="userSpaceOnUse" cx="${W * 0.35}" cy="${horizon}" r="${W * 0.7}">
      <stop offset="0" stop-color="${PAL.skyGlow}" stop-opacity="0.35"/><stop offset="1" stop-color="${PAL.skyGlow}" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="far" gradientUnits="userSpaceOnUse" x1="0" y1="${horizon + 6 - 14}" x2="0" y2="${horizon + 6 + 80}">
      <stop offset="0" stop-color="${PAL.hillFar}"/><stop offset="1" stop-color="${PAL.hillMid}"/>
    </linearGradient>
    <linearGradient id="mid" gradientUnits="userSpaceOnUse" x1="0" y1="${houseBaseY + 6 - 20}" x2="0" y2="${houseBaseY + 6 + 120}">
      <stop offset="0" stop-color="${PAL.hillMid}"/><stop offset="1" stop-color="${PAL.hillNear}"/>
    </linearGradient>
    <linearGradient id="ground" gradientUnits="userSpaceOnUse" x1="0" y1="${crestY - 18}" x2="0" y2="${H}">
      <stop offset="0" stop-color="${PAL.hillNear}"/><stop offset="${(60 / (H - crestY + 18)).toFixed(3)}" stop-color="${PAL.ground}"/>
      <stop offset="1" stop-color="${PAL.groundDeep}"/>
    </linearGradient>
  </defs>
  <rect width="${W}" height="${H}" fill="${PAL.skyHorizon}"/>
  <rect width="${W}" height="${skyEnd}" fill="url(#sky)"/>
  <rect width="${W}" height="${H}" fill="url(#haze)"/>
  <path d="${hillPts(horizon - 26, 10, 1.9, 1.6)}" fill="${mix(PAL.hillFar, PAL.skyHorizon, 0.35)}"/>
  <path d="${hillPts(horizon + 6, 14, 0.6, 2.2)}" fill="url(#far)"/>
  <path d="${hillPts(houseBaseY + 6, 9, 2.1, 1.3)}" fill="url(#mid)"/>
  <path d="${hillPts(crestY, 7, 4.2, 1.7)}" fill="url(#ground)"/>
</svg>
`;
}

async function render(page, svg, size, { css = "", transparent = false, w = size, h = size } = {}) {
  await page.setViewportSize({ width: w, height: h });
  const body = svg.replace(/<svg([^>]*?)width="[^"]*"\s*height="[^"]*"/, `<svg$1width="${w}" height="${h}"`);
  await page.setContent(
    `<!doctype html><html><head><style>html,body{margin:0;background:${transparent ? "transparent" : "#000"}}svg{display:block}${css}</style></head><body>${body}</body></html>`,
  );
  return page.screenshot({ omitBackground: transparent, type: "png" });
}

/** Drops the alpha channel losslessly (PNG → BMP → PNG via sips). */
function stripAlpha(file) {
  const bmp = file.replace(/\.png$/, ".tmp.bmp");
  execFileSync("sips", ["-s", "format", "bmp", file, "--out", bmp], { stdio: "ignore" });
  execFileSync("sips", ["-s", "format", "png", bmp, "--out", file], { stdio: "ignore" });
  rmSync(bmp);
  const info = execFileSync("sips", ["-g", "hasAlpha", file], { encoding: "utf8" });
  if (!/hasAlpha: no/.test(info)) throw new Error(`${file} still has alpha`);
}

mkdirSync(iconOut, { recursive: true });
mkdirSync(launchOut, { recursive: true });
const iconSvg = readFileSync(svgPath, "utf8");
const darkSvg = readFileSync(resolve(iconDir, "duskwick-icon-dark.svg"), "utf8");
const tintedSvg = readFileSync(resolve(iconDir, "duskwick-icon-tinted.svg"), "utf8");
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  const any = resolve(iconOut, "AppIcon-1024.png");
  writeFileSync(any, await render(page, iconSvg, 1024));
  stripAlpha(any);
  const dark = resolve(iconOut, "AppIcon-Dark-1024.png");
  writeFileSync(dark, await render(page, darkSvg, 1024, { transparent: true }));
  const tinted = resolve(iconOut, "AppIcon-Tinted-1024.png");
  writeFileSync(tinted, await render(page, tintedSvg, 1024, { transparent: true }));

  const ls = launchSvg();
  writeFileSync(resolve(launchOut, "launch-dusk.svg"), ls);
  const launchPng = resolve(launchOut, "launch-dusk.png");
  // 2x of the 390 x 844 pt artboard: stretched (scaleToFill) on every phone; soft gradients scale cleanly.
  writeFileSync(launchPng, await render(page, ls, 0, { w: 780, h: 1688 }));
  stripAlpha(launchPng);
} finally {
  await browser.close();
}

// ---------- asset catalog ----------
const iconSet = resolve(xcassets, "AppIcon.appiconset");
rmSync(iconSet, { recursive: true, force: true });
mkdirSync(iconSet, { recursive: true });
for (const f of ["AppIcon-1024.png", "AppIcon-Dark-1024.png", "AppIcon-Tinted-1024.png"]) copyFileSync(resolve(iconOut, f), resolve(iconSet, f));
const entry = (filename, appearance) => ({
  ...(appearance ? { appearances: [{ appearance: "luminosity", value: appearance }] } : {}),
  filename,
  idiom: "universal",
  platform: "ios",
  size: "1024x1024",
});
writeFileSync(
  resolve(iconSet, "Contents.json"),
  JSON.stringify(
    {
      images: [entry("AppIcon-1024.png"), entry("AppIcon-Dark-1024.png", "dark"), entry("AppIcon-Tinted-1024.png", "tinted")],
      info: { author: "xcode", version: 1 },
    },
    null,
    2,
  ) + "\n",
);
const launchSet = resolve(xcassets, "LaunchDusk.imageset");
rmSync(launchSet, { recursive: true, force: true });
mkdirSync(launchSet, { recursive: true });
copyFileSync(resolve(launchOut, "launch-dusk.png"), resolve(launchSet, "launch-dusk.png"));
writeFileSync(
  resolve(launchSet, "Contents.json"),
  JSON.stringify({ images: [{ filename: "launch-dusk.png", idiom: "universal" }], info: { author: "xcode", version: 1 } }, null, 2) + "\n",
);
console.log(`icon ← ${iconDir}/duskwick-icon{,-dark,-tinted}.svg\n  ${iconOut}/AppIcon{,-Dark,-Tinted}-1024.png\nlaunch ← palette.ts\n  ${launchOut}/launch-dusk.{svg,png}\nasset catalog updated: AppIcon.appiconset, LaunchDusk.imageset`);
